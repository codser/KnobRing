# Writes src/bridge/panel/icons.js from VectorIcons.cs so the Premiere panel uses the same line icons.
import re, json, os
root = os.path.join(os.path.dirname(__file__), '..', 'src')
src = open(os.path.join(root, 'VectorIcons.cs'), encoding='utf-8').read()
consts = dict(re.findall(r'const string (\w+) = "([^"]*)";', src))
icons = {}
for name, expr in re.findall(r'\{"(\w+)",\s*(.+?)\},\n', src):
    parts = [p.strip() for p in expr.split('+')]
    d = ''.join(consts.get(p, p.strip('"')) for p in parts)
    icons[name] = d
open(os.path.join(root, 'bridge', 'panel', 'icons.js'), 'w', encoding='utf-8').write(
    '// generated by tools/make_panel_icons.py from VectorIcons.cs\nwindow.KR_ICONS = ' + json.dumps(icons, indent=0) + ';\n')
print(len(icons), 'icons')
